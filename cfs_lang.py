def detect_start_lang():
    """Startsprache: gespeicherte Wahl > Systemsprache (en/* -> en,
    sonst de). Nur Codes mit echten Inhalten (nicht-leeres Dict)."""
    import locale
    import os
    cfg = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "data", "lang.cfg")
    try:
        with open(cfg, encoding="utf-8") as f:
            code = f.read().strip().lower()[:2]
        if code in STRINGS and STRINGS[code]:
            return code
    except Exception:
        pass
    try:
        loc, _ = locale.getdefaultlocale()
    except Exception:
        loc = ""
    if (loc or "").lower().startswith("en"):
        return "en" if STRINGS.get("en") else DEFAULT_LANG
    return DEFAULT_LANG


def save_start_lang(code):
    """Sprachwahl merken (data/lang.cfg). Fehler werden ignoriert."""
    import os
    try:
        cfg = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "data", "lang.cfg")
        with open(cfg, "w", encoding="utf-8") as f:
            f.write(code.strip().lower()[:2])
    except Exception:
        pass


def set_lang(code):
    """Aktive Sprache umschalten ('de'/'en'). Gibt True bei Erfolg."""
    global LANG
    if code in STRINGS:
        LANG = code
        return True
    return False


def t(key, lang=None):
    """Text für Schlüssel holen, Fallback Deutsch, dann Schlüssel."""
    code = lang or LANG
    d = STRINGS.get(code, STRINGS[DEFAULT_LANG])
    if key in d:
        return d[key]
    return STRINGS[DEFAULT_LANG].get(key, key)


def tf(key, lang=None, **kw):
    """Text holen und {Platzhalter} füllen (Fehler -> unformatierter Text)."""
    txt = t(key, lang)
    try:
        return txt.format(**kw)
    except Exception:
        return txt


def level_name(key, lang=None):
    """Stufenname (ohne Nummer) in der aktiven Sprache, Fallback Deutsch."""
    names = LEVEL_NAMES.get(lang or LANG, LEVEL_NAMES[DEFAULT_LANG])
    return names.get(key, LEVEL_NAMES[DEFAULT_LANG].get(key, key))


def fmt_thousands(n, lang=None):
    """Ganzzahl mit Tausendertrenner (de: Punkt, sonst Komma)."""
    code = lang or LANG
    sep = "." if code in ("de", "es", "nl", "it") else (" " if code == "fr" else ",")
    return f"{int(n):,d}".replace(",", sep)


def fmt_decimal(txt, lang=None):
    """Dezimalpunkt-Text ('2.3') in die Landesschreibweise (de: Komma)."""
    return txt.replace(".", ",") if (lang or LANG) in ("de", "es", "fr", "nl", "it") else txt
